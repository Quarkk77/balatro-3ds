-- gen_credits.lua: generates game/ui_credits_data.c from the static parts of
-- G.UIDEF.credits() in UI_definitions.lua (the credits are ~900 lines of
-- literal UI tables). Run with any Lua 5.1 / LuaJIT:
--   luajit gen_credits.lua <path to src_lua> <output file>
local SRC = arg[1] or '../../src_lua'
local OUT = arg[2] or '../game/ui_credits_data.c'

-- ---------------------------------------------------------------- mocks
local function colour_proxy(path)
  return setmetatable({ __col = path }, { __index = function(t, k)
    if type(k) == 'number' then return 1 end
    local v = colour_proxy(path .. '.' .. k); rawset(t, k, v); return v end })
end
G = { UIT = { T = 1, B = 2, C = 3, R = 4, O = 5, ROOT = 7 }, C = colour_proxy('G.C'), UIDEF = {}, FUNCS = {},
      F_EXTERNAL_LINKS = false, ASSET_ATLAS = setmetatable({}, { __index = function(_, k) return { __atlas = k } end }),
      CARD_W = 2.4 * 35 / 41, CARD_H = 2.4 * 47 / 41 }
function localize(k) return { __loc = k } end
function UIBox_button(args) return { __button = args } end
function create_tabs(args) return { __tabs = args } end
function create_option_cycle(args) return { __cycle = args } end
function create_UIBox_generic_options(args) return args end
function Moveable() return { __moveable = true } end
function Sprite(x, y, w, h, atlas, pos) return { __sprite = { w = w, h = h, atlas = atlas, pos = pos } } end
function lighten(c, a) return { __col = 'lighten(' .. c.__col .. ', ' .. a .. ')' } end
function darken(c, a) return { __col = 'darken(' .. c.__col .. ', ' .. a .. ')' } end
function mix_colours(a, b, p) return { __col = 'mix_colours(' .. a.__col .. ', ' .. b.__col .. ', ' .. p .. ')' } end
function adjust_alpha(c, a) return { __col = 'adjust_alpha(' .. c.__col .. ', ' .. a .. ')' } end

local mocks = { UIBox_button = UIBox_button, create_tabs = create_tabs, create_option_cycle = create_option_cycle,
                create_UIBox_generic_options = create_UIBox_generic_options }
local chunk = assert(loadfile(SRC .. '/functions/UI_definitions.lua'))
chunk()
for k, v in pairs(mocks) do _G[k] = v end

local credits = G.UIDEF.credits()
local tabs = credits.contents[1].nodes[1].__tabs.tabs

-- ---------------------------------------------------------------- emitter
local out = {}
local function w(s) out[#out + 1] = s end

local function cstr(s)
  return '"' .. tostring(s):gsub('\\', '\\\\'):gsub('"', '\\"'):gsub('\n', '\\n') .. '"'
end
local function num(n) return string.format('%.17g', n) end

local UITN = { [1] = 'UIT_T', [2] = 'UIT_B', [3] = 'UIT_C', [4] = 'UIT_R', [5] = 'UIT_O', [7] = 'UIT_ROOT' }

local function emit_value(k, v)
  if type(v) == 'table' and v.__col then return v.__col end
  if type(v) == 'table' and v.__loc then return '(char *)localize_key(' .. cstr(v.__loc) .. ')' end
  if type(v) == 'number' then return num(v) end
  if type(v) == 'boolean' then return v and 'true' or 'false' end
  if type(v) == 'string' then
    if k == 'text' then return '(char *)' .. cstr(v) end
    return cstr(v)
  end
  error('unsupported value for ' .. k .. ': ' .. tostring(v))
end

local ALLOWED = { align = 1, padding = 1, colour = 1, r = 1, emboss = 1, minh = 1, minw = 1, maxw = 1, maxh = 1, outline_colour = 1,
                  outline = 1, text = 1, scale = 1, shadow = 1, w = 1, h = 1, no_fill = 1, hover = 1, juice = 1, line_emboss = 1 }

local function emit_cfg(cfg)
  local parts = {}
  local keys = {}
  for k in pairs(cfg or {}) do keys[#keys + 1] = k end
  table.sort(keys)
  for _, k in ipairs(keys) do
    if not ALLOWED[k] then error('unsupported config key ' .. k) end
    parts[#parts + 1] = '.' .. k .. ' = ' .. emit_value(k, cfg[k])
  end
  return 'CFG(' .. (#parts > 0 and table.concat(parts, ', ') or '.align = NULL') .. ')'
end

local function emit_node(n, depth)
  local ind = string.rep('    ', depth)
  if n.__button then
    local a = n.__button
    local label = a.label and a.label[1]
    return ind .. 'UIBUTTON(.label = { ' .. (type(label) == 'table' and ('localize_key(' .. cstr(label.__loc) .. ')') or cstr(label)) .. ' }, .nlabel = 1)'
  end
  if n.__sprite then error('sprite in static credits tab') end
  local children = {}
  -- pairs() over nodes skips nils, like the engine does
  local idx = {}
  for k in pairs(n.nodes or {}) do idx[#idx + 1] = k end
  table.sort(idx)
  for _, k in ipairs(idx) do children[#children + 1] = emit_node(n.nodes[k], depth + 1) end
  local s = ind .. 'UIN(' .. UITN[n.n] .. ', ' .. emit_cfg(n.config)
  if #children > 0 then s = s .. ',\n' .. table.concat(children, ',\n') end
  return s .. ')'
end

w('/* ui_credits_data.c - GENERATED by tools/gen_credits.lua from UI_definitions.lua. Do not edit. */')
w('#include "game.h"')
w('')
local static_tabs = {}
for i, t in ipairs(tabs) do
  if t.label ~= 'Collabs' then
    local root = t.tab_definition_function()
    w('static UIDef *credits_tab_' .. i .. '(void *arg) {')
    w('    (void)arg;')
    w('    return')
    w(emit_node(root, 1) .. ';')
    w('}')
    w('')
    static_tabs[#static_tabs + 1] = { i = i, label = t.label }
  end
end

-- collab credits data
local collab_tab
for i, t in ipairs(tabs) do if t.label == 'Collabs' then collab_tab = i; t.tab_definition_function() end end
local names = {}
for k in pairs(G.collab_credits) do names[#names + 1] = k end
table.sort(names)
w('const CollabCredit CREDITS_COLLABS[] = {')
for _, k in ipairs(names) do
  local v = G.collab_credits[k]
  local ml = {}
  for _, l in ipairs(v.ml_text or {}) do ml[#ml + 1] = cstr(l) end
  w(string.format('    { %s, %s, %s, %s, { %s }, %d },', cstr(k), v.artist and cstr(v.artist) or 'NULL', v.artist_link and cstr(v.artist_link) or 'NULL',
    cstr(v.art), table.concat(ml, ', '), #ml))
end
w('};')
w('const int CREDITS_N_COLLABS = ' .. #names .. ';')
w('')
w('const CreditsTab CREDITS_TABS[] = {')
for i, t in ipairs(tabs) do
  if t.label == 'Collabs' then w('    { "Collabs", NULL },')
  else w('    { ' .. cstr(t.label) .. ', credits_tab_' .. i .. ' },') end
end
w('};')
w('const int CREDITS_N_TABS = ' .. #tabs .. ';')

local f = assert(io.open(OUT, 'w'))
f:write(table.concat(out, '\n'), '\n')
f:close()
print('wrote ' .. OUT .. ' (' .. #tabs .. ' tabs, ' .. #names .. ' collabs)')
