#!/bin/sh
# gen_asset_list.sh - writes game/asset_list.c: the names of the game files balatro_c expects
# in sdmc:/3ds/balatro_c/assets (the set src_install/install_balatro_c.sh copies from the
# user's own copy of Balatro). Only file names, no game content. Run from src_3ds/ after
# changing that set:  sh tools/gen_asset_list.sh ../src_lua > game/asset_list.c
src="${1:-../src_lua}"
cd "$src" || exit 1
echo '/* generated by tools/gen_asset_list.sh: the game files expected in the assets folder */'
echo '#include <stddef.h>'
echo 'const char *const ASSET_LIST[] = {'
{
    find resources/textures/1x resources/sounds resources/shaders localization -type f
    for f in m6x11plus.ttf NotoSans-Bold.ttf NotoSansJP-Bold.ttf NotoSansKR-Bold.ttf NotoSansSC-Bold.ttf NotoSansTC-Bold.ttf; do
        echo "resources/fonts/$f"
    done
} | LC_ALL=C sort | sed 's/.*/    "&",/'
echo '};'
echo 'const size_t ASSET_COUNT = sizeof ASSET_LIST / sizeof ASSET_LIST[0];'
